"""Render the schema as Mermaid class diagrams, one per subset.

Regenerate the Markdown file with: just gen-graph
"""

import sys

from linkml.generators.docgen import DocGenerator
from linkml_runtime.utils.schemaview import SchemaView


def render(schema_path: str) -> str:
    sv = SchemaView(schema_path)
    classes, enums = sv.all_classes(imports=False), sv.all_enums(imports=False)
    members, edges = {}, {}
    for c in classes.values():
        lines, own_edges = members[c.name], edges[c.name] = [], []
        if c.abstract:
            lines.append("<<abstract>>")
        if c.is_a:
            own_edges.append(f"{c.is_a} <|-- {c.name}")
        # Own slots only: inherited ones are drawn once, on the parent.
        for name in [*c.slots, *c.attributes]:
            s = sv.induced_slot(name, c.name)
            card = DocGenerator.cardinality(s)
            if s.range in classes:
                arrow = "*--" if s.inlined or s.inlined_as_list else "-->"
                own_edges.append(f'{c.name} {arrow} "{card}" {s.range} : {name}')
            elif s.range in enums:
                own_edges.append(f"{c.name} ..> {s.range} : {name}")
            else:
                lines.append(f"+{s.range} {name} [{card}]")
    for e in enums.values():
        members[e.name], edges[e.name] = ["<<enumeration>>", *e.permissible_values], []

    untagged = [n for n in members if not sv.get_element(n).in_subset]
    assert not untagged, f"add in_subset to: {', '.join(untagged)}"

    out = ["# Ontology graph", "",
           "Generated by `just gen-graph` from the schema. Do not edit.", "",
           "One diagram per subset. Empty boxes are classes from another subset.", "",
           "`<|--` is_a · `*--` contains (inlined) · `-->` references by id · `..>` enum value"]
    for subset in sv.all_subsets():
        out += ["", f"## {subset.capitalize()}", "",
                sv.get_subset(subset).description, "",
                "```mermaid", "classDiagram"]
        names = [n for n in members if subset in sv.get_element(n).in_subset]
        for name in names:
            out.append(f"class {name} {{")
            out += [f"  {line}" for line in members[name]]
            out.append("}")
        out += [edge for name in names for edge in edges[name]]
        out.append("```")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    sys.stdout.write(render(sys.argv[1]))
